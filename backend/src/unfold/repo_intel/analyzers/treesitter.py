class _JvmMixin(_Extractor):
    """Route/entity helpers shared by the Java and Kotlin extractors (annotation-driven frameworks)."""

    def jvm_import(self, node: Node, module: str, *, wildcard: bool, alias: str | None, static: bool) -> None:
        segs = module.split(".")
        resolved: str | None = None
        resolved_dir: str | None = None
        if self.index is not None:
            if wildcard:
                resolved_dir = self.index.dir_with_suffix("/".join(segs))
            else:
                cands = [segs, segs[:-1]] if static else [segs]
                for cs in cands:
                    if not cs:
                        continue
                    for ext in (".java", ".kt"):
                        resolved = self.index.file_with_suffix("/".join(cs) + ext)
                        if resolved:
                            break
                    if resolved:
                        break
        external = resolved is None and resolved_dir is None
        package = ".".join(segs[:2]) if external else None
        name = segs[-1]
        self.add_import(
            module,
            node,
            names=["*"] if wildcard else [name],
            alias=alias,
            resolved_path=resolved,
            resolved_dir=resolved_dir,
            external=external,
            package=package,
        )
        if not wildcard:
            local = alias or name
            if external:
                self.bind(local, Binding(kind="symbol", attr=name, external=module))
            else:
                self.bind(local, Binding(kind="symbol", path=resolved, attr=name))

    def class_routes(self, name: str, anns: dict[str, list[str]], node: Node) -> tuple[str | None, str]:
        """(prefix or None when not a controller, framework)."""
        if "Path" in anns and not ({"RestController", "Controller"} & anns.keys()):
            prefix = (anns.get("Path") or [""])[0]
            self.add_router(name, "jaxrs", node, prefix=prefix)
            return prefix, "jaxrs"
        if {"RestController", "Controller"} & anns.keys() or "RequestMapping" in anns:
            prefix = (anns.get("RequestMapping") or [""])[0]
            self.add_router(name, "spring", node, prefix=prefix)
            self.add_app_object("spring")
            return prefix, "spring"
        return None, ""

    def method_routes(
        self,
        cls: str,
        qual: str,
        anns: dict[str, list[str]],
        methods_of: dict[str, list[str]],
        prefix: str | None,
        framework: str,
        node: Node,
    ) -> None:
        if prefix is None:
            return
        if framework == "jaxrs":
            verbs = [a for a in anns if a in _JAXRS_METHODS]
            if not verbs:
                return
            path = (anns.get("Path") or ["/"])[0] or "/"
            for v in verbs:
                self.add_route(
                    v, path, node, "jaxrs", router=cls, handler=qual, full_path=_join_path(prefix, path)
                )
            return
        for ann, verb in _SPRING_MAPPINGS.items():
            if ann not in anns:
                continue
            paths = anns[ann] or ["/"]
            verbs = [verb] if verb else methods_of.get(ann) or ["ANY"]
            for path in paths:
                for v in verbs:
                    self.add_route(
                        v,
                        path or "/",
                        node,
                        "spring",
                        router=cls,
                        handler=qual,
                        full_path=_join_path(prefix, path),
                    )

    def method_tasks(self, qual: str, anns: dict[str, list[str]], node: Node) -> None:
        if "Scheduled" in anns:
            self.fa.tasks.append(
                TaskDef(name=qual, technology="spring_scheduler", line=self.line(node), symbol=qual)
            )
        for ann, tech in _JVM_LISTENERS.items():
            if ann in anns:
                name = (anns[ann] or [qual])[0] or qual
                self.fa.tasks.append(TaskDef(name=name, technology=tech, line=self.line(node), symbol=qual))


class _JavaExtractor(_JvmMixin):
    type_decls: Final = frozenset(
        {
            "class_declaration",
            "interface_declaration",
            "enum_declaration",
            "record_declaration",
            "annotation_type_declaration",
        }
    )

    def parts(self, node: Node | None) -> list[str] | None:
        if node is None:
            return None
        t = node.type
        if t in ("identifier", "this", "super", "type_identifier"):
            return [self.text(node)]
        if t == "field_access":
            base = self.parts(node.child_by_field_name("object"))
            field = node.child_by_field_name("field")
            return [*base, self.text(field)] if base is not None and field is not None else None
        if t == "scoped_identifier":
            base = self.parts(node.child_by_field_name("scope"))
            name = node.child_by_field_name("name")
            return [*base, self.text(name)] if base is not None and name is not None else None
        if t == "parenthesized_expression":
            inner = node.named_children
            return self.parts(inner[0]) if inner else None
        return None

    def annotations(self, node: Node) -> list[Node]:
        mods = next((c for c in node.children if c.type == "modifiers"), None)
        if mods is None:
            return []
        return [c for c in mods.named_children if c.type in ("annotation", "marker_annotation")]

    def ann_name(self, ann: Node) -> str:
        return self.text(ann.child_by_field_name("name")).rsplit(".", 1)[-1]

    def ann_strings(self, value: Node | None) -> list[str]:
        if value is None:
            return []
        s = self.string_value(value)
        if s is not None:
            return [s]
        if value.type == "element_value_array_initializer":
            return [v for v in (self.string_value(c) for c in value.named_children) if v is not None]
        return []

    def ann_info(self, node: Node) -> tuple[dict[str, list[str]], dict[str, list[str]], list[str]]:
        """({annotation: path-ish strings}, {annotation: request methods}, [annotation names])."""
        info: dict[str, list[str]] = {}
        methods: dict[str, list[str]] = {}
        names: list[str] = []
        for ann in self.annotations(node):
            name = self.ann_name(ann)
            names.append(name)
            values: list[str] = []
            args = ann.child_by_field_name("arguments")
            if args is not None:
                for a in args.named_children:
                    if a.type == "element_value_pair":
                        key = self.text(a.child_by_field_name("key"))
                        val = a.child_by_field_name("value")
                        if key in ("value", "path", "topics", "queues", "destination", "name", "cron"):
                            values += self.ann_strings(val)
                        elif key == "method" and val is not None:
                            vs = (
                                val.named_children if val.type == "element_value_array_initializer" else [val]
                            )
                            methods[name] = [self.text(v).rsplit(".", 1)[-1].upper() for v in vs]
                    else:
                        values += self.ann_strings(a)
            info[name] = values
        return info, methods, names

    def modifiers_text(self, node: Node) -> set[str]:
        mods = next((c for c in node.children if c.type == "modifiers"), None)
        if mods is None:
            return set()
        return {self.text(c) for c in mods.children if not c.is_named}

    def visit(self, node: Node) -> None:
        t = node.type
        if t == "import_declaration":
            self.import_decl(node)
        elif t in self.type_decls:
            self.type_decl(node)
        elif t in ("method_declaration", "constructor_declaration"):
            self.visit_body(node, None)
        elif t == "method_invocation":
            obj = node.child_by_field_name("object")
            name = node.child_by_field_name("name")
            base = self.parts(obj) if obj is not None else []
            if base is not None and name is not None:
                self.add_call([*base, self.text(name)], node)
            self.visit_children(node)
        elif t == "object_creation_expression":
            p = self.parts(node.child_by_field_name("type"))
            if p:
                self.add_call(p, node)
            self.visit_children(node)
        else:
            self.visit_children(node)

    def import_decl(self, node: Node) -> None:
        target = next((c for c in node.named_children if c.type in ("scoped_identifier", "identifier")), None)
        if target is None:
            return
        wildcard = any(c.type == "asterisk" for c in node.children)
        static = any(c.type == "static" for c in node.children)
        self.jvm_import(node, self.text(target), wildcard=wildcard, alias=None, static=static)

    def type_decl(self, node: Node) -> None:
        name_n = node.child_by_field_name("name")
        if name_n is None or self.fn_depth:
            self.visit_body(node, None)
            return
        name = self.text(name_n)
        kind: SymbolKind = (
            "interface" if node.type in ("interface_declaration", "annotation_type_declaration") else "class"
        )
        bases: list[str] = []
        sup = node.child_by_field_name("superclass")
        if sup is not None:
            bases += [self.text(c) for c in sup.named_children]
        for field_name in ("interfaces",):
            f = node.child_by_field_name(field_name)
            if f is not None:
                for tl in f.named_children:
                    bases += (
                        [self.text(c) for c in tl.named_children]
                        if tl.type == "type_list"
                        else [self.text(tl)]
                    )
        for c in node.named_children:
            if c.type == "extends_interfaces":
                for tl in c.named_children:
                    bases += (
                        [self.text(x) for x in tl.named_children]
                        if tl.type == "type_list"
                        else [self.text(tl)]
                    )
        anns, _methods, ann_names = self.ann_info(node)
        mods = self.modifiers_text(node)
        body = node.child_by_field_name("body")
        sym = self.add_symbol(
            name,
            kind,
            node,
            decorators=ann_names,
            bases=bases,
            exported="public" in mods,
            signature=self.signature(node, body),
        )
        prefix, framework = self.class_routes(name, anns, node)
        entity = "Entity" in anns or "Document" in anns
        table: str | None = (anns.get("Table") or anns.get("Document") or [""])[0] or None
        if "Table" in anns and not anns["Table"]:
            table = self.named_ann_value(node, "Table", "name")
        fields: list[FieldDef] = []
        self.containers.append(sym.qualname)
        self.scope.append(sym.qualname)
        try:
            for member in self.members(body):
                mt = member.type
                if mt in ("method_declaration", "constructor_declaration", "compact_constructor_declaration"):
                    self.method(member, sym, prefix, framework)
                elif mt == "field_declaration":
                    if entity:
                        fields += self.entity_fields(member)
                    self.visit_children(member)
                elif mt in self.type_decls:
                    self.type_decl(member)
                else:
                    self.visit(member)
        finally:
            self.containers.pop()
            self.scope.pop()
        if entity:
            self.fa.schemas.append(
                SchemaDef(
                    name=name,
                    schema_kind="orm_model",
                    start_line=self.line(node),
                    end_line=self.end_line(node),
                    fields=fields,
                    symbol=sym.qualname,
                    table=table,
                )
            )

    def named_ann_value(self, node: Node, ann_name: str, key: str) -> str | None:
        for ann in self.annotations(node):
            if self.ann_name(ann) != ann_name:
                continue
            args = ann.child_by_field_name("arguments")
            for a in args.named_children if args is not None else []:
                if a.type == "element_value_pair" and self.text(a.child_by_field_name("key")) == key:
                    return self.string_value(a.child_by_field_name("value"))
        return None

    def members(self, body: Node | None) -> Iterator[Node]:
        if body is None:
            return
        for c in body.named_children:
            if c.type == "enum_body_declarations":
                yield from c.named_children
            else:
                yield c

    def entity_fields(self, member: Node) -> list[FieldDef]:
        mods = self.modifiers_text(member)
        anns, _m, ann_names = self.ann_info(member)
        if "static" in mods or "Transient" in anns:
            return []
        type_n = member.child_by_field_name("type")
        type_text = self.text(type_n) if type_n is not None else None
        attrs: list[str] = []
        relation: str | None = None
        for a in ann_names:
            if a == "Id" or a == "EmbeddedId":
                attrs.append("primary_key")
            elif a == "GeneratedValue":
                attrs.append("generated")
            elif a in _JPA_RELATIONS:
                attrs.append(a[0].lower() + a[1:])
                if a in ("ManyToOne", "OneToOne"):
                    attrs.append("fk")
                target = type_n
                if type_n is not None and type_n.type == "generic_type":
                    targs = next((c for c in type_n.named_children if c.type == "type_arguments"), None)
                    if targs is not None and targs.named_children:
                        target = targs.named_children[-1]
                relation = self.text(target) if target is not None else None
            elif a == "JoinColumn" and "fk" not in attrs:
                attrs.append("fk")
        if "Column" in anns:
            for ann in self.annotations(member):
                if self.ann_name(ann) != "Column":
                    continue
                args = ann.child_by_field_name("arguments")
                for p in args.named_children if args is not None else []:
                    if p.type != "element_value_pair":
                        continue
                    key = self.text(p.child_by_field_name("key"))
                    val = self.text(p.child_by_field_name("value"))
                    if key == "unique" and val == "true":
                        attrs.append("unique")
                    elif key == "nullable" and val == "false":
                        attrs.append("not_null")
        out: list[FieldDef] = []
        for d in member.children_by_field_name("declarator"):
            n = d.child_by_field_name("name")
            if n is not None:
                out.append(
                    FieldDef(name=self.text(n), type=type_text, relation=relation, attributes=list(attrs))
                )
        return out

    def method(self, member: Node, cls: SymbolDef, prefix: str | None, framework: str) -> None:
        name_n = member.child_by_field_name("name")
        name = self.text(name_n) if name_n is not None else cls.name
        anns, methods_of, ann_names = self.ann_info(member)
        mods = self.modifiers_text(member)
        body = member.child_by_field_name("body")
        sym = self.add_symbol(
            name,
            "method",
            member,
            parent=cls.qualname,
            decorators=ann_names,
            exported="public" in mods,
            signature=self.signature(member, body),
        )
        self.method_routes(cls.name, sym.qualname, anns, methods_of, prefix, framework, member)
        self.method_tasks(sym.qualname, anns, member)
        self.visit_body(body, sym.qualname)


