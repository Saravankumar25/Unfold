class _PhpExtractor(_Extractor):
    def __init__(
        self,
        file: InventoryFile,
        src: bytes,
        fa: FileAnalysis,
        index: _RepoIndex | None,
        aliases: Mapping[str, Sequence[str]],
        grammar: str,
    ) -> None:
        super().__init__(file, src, fa, index, aliases, grammar)
        self.namespace: str | None = None
        self.route_prefix: list[str] = []
        self.imported_classes: set[str] = set()
        if file.path.endswith("routes/api.php"):
            self.route_prefix.append("api")

    def php_static_classes(self) -> set[str]:
        return {c for c in self.imported_classes if c}

    def parts(self, node: Node | None) -> list[str] | None:
        if node is None:
            return None
        t = node.type
        if t in ("name", "relative_scope"):
            return [self.text(node)]
        if t == "qualified_name":
            return [self.text(node).rsplit("\\", 1)[-1]]
        if t == "variable_name":
            return [self.text(node).lstrip("$")]
        if t in ("member_access_expression", "nullsafe_member_access_expression"):
            base = self.parts(node.child_by_field_name("object"))
            name = node.child_by_field_name("name")
            return [*base, self.text(name)] if base is not None and name is not None else None
        if t == "parenthesized_expression":
            inner = node.named_children
            return self.parts(inner[0]) if inner else None
        return None

    def args(self, call: Node) -> list[Node]:
        a = call.child_by_field_name("arguments")
        out: list[Node] = []
        for c in a.named_children if a is not None else []:
            if c.type == "argument":
                inner = [x for x in c.named_children if x.type != "name"] or c.named_children
                if inner:
                    out.append(inner[-1])
        return out

    def resolve_class(self, fqcn: str) -> str | None:
        if self.index is None:
            return None
        segs = [s for s in fqcn.split("\\") if s]
        if not segs:
            return None
        cands = ["/".join(segs) + ".php", "/".join([segs[0].lower(), *segs[1:]]) + ".php"]
        if len(segs) > 1:
            cands.append("/".join(segs[1:]) + ".php")
        for c in cands:
            hit = self.index.file_with_suffix(c)
            if hit:
                return hit
        return None

    def visit(self, node: Node) -> None:
        t = node.type
        if t == "namespace_definition":
            name = node.child_by_field_name("name")
            self.namespace = self.text(name) if name is not None else None
            self.visit_children(node)
        elif t == "namespace_use_declaration":
            self.use_decl(node)
        elif t in (
            "include_expression",
            "include_once_expression",
            "require_expression",
            "require_once_expression",
        ):
            self.include(node)
        elif t in ("class_declaration", "interface_declaration", "trait_declaration", "enum_declaration"):
            self.class_decl(node)
        elif t == "function_definition":
            self.function(node, None)
        elif t in ("function_call_expression",):
            p = self.parts(node.child_by_field_name("function"))
            if p:
                self.add_call(p, node)
                if p == ["dispatch"]:
                    for a in self.args(node):
                        if a.type == "object_creation_expression":
                            cp = self.parts(
                                next(
                                    (c for c in a.named_children if c.type in ("name", "qualified_name")),
                                    None,
                                )
                            )
                            if cp:
                                self.fa.publishes.append(
                                    PublishRef(
                                        caller=self.caller(),
                                        task=cp[-1],
                                        technology="laravel_queue",
                                        line=self.line(node),
                                    )
                                )
            self.visit_children(node)
        elif t in ("member_call_expression", "nullsafe_member_call_expression"):
            self.member_call(node)
        elif t == "scoped_call_expression":
            self.scoped_call(node)
        elif t == "object_creation_expression":
            cls = next((c for c in node.named_children if c.type in ("name", "qualified_name")), None)
            p = self.parts(cls)
            if p:
                self.add_call(p, node)
            self.visit_children(node)
        else:
            self.visit_children(node)

    def use_decl(self, node: Node) -> None:
        prefix_n = next((c for c in node.named_children if c.type == "namespace_name"), None)
        group = next((c for c in node.named_children if c.type == "namespace_use_group"), None)
        clauses: list[tuple[str, str | None]] = []
        if group is not None:
            prefix = self.text(prefix_n) if prefix_n is not None else ""
            for cl in (
                c
                for c in group.named_children
                if c.type in ("namespace_use_clause", "namespace_use_group_clause")
            ):
                nm = next(
                    (c for c in cl.named_children if c.type in ("name", "qualified_name", "namespace_name")),
                    None,
                )
                al = cl.child_by_field_name("alias")
                if nm is not None:
                    clauses.append((f"{prefix}\\{self.text(nm)}", self.text(al) if al is not None else None))
        else:
            for cl in (c for c in node.named_children if c.type == "namespace_use_clause"):
                nm = next(
                    (c for c in cl.named_children if c.type in ("qualified_name", "name", "namespace_name")),
                    None,
                )
                al = cl.child_by_field_name("alias")
                if al is None:
                    names = [c for c in cl.named_children if c.type == "name"]
                    al = names[-1] if nm is not None and nm.type == "qualified_name" and names else None
                if nm is not None:
                    clauses.append(
                        (self.text(nm).lstrip("\\"), self.text(al) if al is not None and al != nm else None)
                    )
        root = (self.namespace or "").split("\\")[0]
        for fqcn, alias in clauses:
            resolved = self.resolve_class(fqcn)
            segs = fqcn.split("\\")
            internal = resolved is not None or (bool(root) and segs[0] == root)
            self.add_import(
                fqcn,
                node,
                names=[segs[-1]],
                alias=alias,
                resolved_path=resolved,
                external=not internal,
                package=segs[0],
            )
            local = alias or segs[-1]
            self.imported_classes.add(local)
            if internal:
                self.bind(local, Binding(kind="symbol", path=resolved, attr=segs[-1]))
            else:
                self.bind(local, Binding(kind="symbol", attr=segs[-1], external=fqcn))

    def include(self, node: Node) -> None:
        spec = next((s for s in (self.string_value(d) for d in self.descendants(node, limit=50)) if s), None)
        if spec is None:
            return
        resolved: str | None = None
        if self.index is not None:
            base = posixpath.normpath(posixpath.join(self.file.directory, spec.lstrip("/")))
            resolved = base if self.index.has(base) else None
        self.add_import(spec, node, resolved_path=resolved, external=False)

    def attributes(self, node: Node) -> list[tuple[str, list[str], dict[str, Node]]]:
        out: list[tuple[str, list[str], dict[str, Node]]] = []
        for group in (c for c in node.named_children if c.type == "attribute_list"):
            for attr in (d for d in self.descendants(group, limit=200) if d.type == "attribute"):
                nm = next((c for c in attr.named_children if c.type in ("name", "qualified_name")), None)
                if nm is None:
                    continue
                positional: list[str] = []
                named: dict[str, Node] = {}
                params = next((c for c in attr.named_children if c.type == "arguments"), None)
                for arg in params.named_children if params is not None else []:
                    if arg.type != "argument":
                        continue
                    key = arg.child_by_field_name("name")
                    val = [c for c in arg.named_children if c is not key]
                    if key is not None and val:
                        named[self.text(key)] = val[-1]
                    elif val:
                        s = self.string_value(val[-1])
                        if s is not None:
                            positional.append(s)
                out.append((self.text(nm).rsplit("\\", 1)[-1], positional, named))
        return out

    def class_decl(self, node: Node) -> None:
        name_n = node.child_by_field_name("name")
        if name_n is None or self.fn_depth:
            self.visit_children(node)
            return
        name = self.text(name_n)
        bases: list[str] = []
        for c in node.named_children:
            if c.type in ("base_clause", "class_interface_clause"):
                bases += [self.text(x) for x in c.named_children]
        body = node.child_by_field_name("body")
        attrs = self.attributes(node)
        sym = self.add_symbol(
            name,
            "interface" if node.type == "interface_declaration" else "class",
            node,
            decorators=[a for a, _, _ in attrs],
            bases=bases,
            exported=True,
            signature=self.signature(node, body),
        )
        prefix: str | None = None
        for a, pos, _named in attrs:
            if a == "Route":
                prefix = pos[0] if pos else ""
        if prefix is not None:
            self.add_router(name, "symfony", node, prefix=prefix)
        base_names = {b.rsplit("\\", 1)[-1] for b in bases}
        is_model = bool(base_names & _ELOQUENT_BASES)
        if "ShouldQueue" in base_names:
            self.fa.tasks.append(
                TaskDef(name=name, technology="laravel_queue", line=self.line(node), symbol=sym.qualname)
            )
        fields: list[FieldDef] = []
        table: str | None = None
        self.containers.append(sym.qualname)
        self.scope.append(sym.qualname)
        try:
            for member in body.named_children if body is not None else []:
                if member.type == "method_declaration":
                    rel = self.method(member, sym, prefix)
                    if is_model and rel is not None:
                        fields.append(rel)
                elif member.type == "property_declaration" and is_model:
                    for el in (c for c in member.named_children if c.type == "property_element"):
                        var = next((c for c in el.named_children if c.type == "variable_name"), None)
                        vname = self.text(var).lstrip("$") if var is not None else ""
                        strings = [
                            s for s in (self.string_value(d) for d in self.descendants(el)) if s is not None
                        ]
                        if vname == "fillable":
                            fields += [FieldDef(name=s) for s in strings]
                        elif vname == "table" and strings:
                            table = strings[0]
                    self.visit_children(member)
                else:
                    self.visit(member)
        finally:
            self.containers.pop()
            self.scope.pop()
        if is_model:
            self.fa.schemas.append(
                SchemaDef(
                    name=name,
                    schema_kind="orm_model",
                    start_line=self.line(node),
                    end_line=self.end_line(node),
                    fields=fields,
                    symbol=sym.qualname,
                    table=table,
                )
            )

    def method(self, member: Node, cls: SymbolDef, prefix: str | None) -> FieldDef | None:
        name_n = member.child_by_field_name("name")
        if name_n is None:
            return None
        name = self.text(name_n)
        body = member.child_by_field_name("body")
        mods = {self.text(c) for c in member.named_children if c.type == "visibility_modifier"}
        attrs = self.attributes(member)
        sym = self.add_symbol(
            name,
            "method",
            member,
            parent=cls.qualname,
            decorators=[a for a, _, _ in attrs],
            exported=not ({"private", "protected"} & mods),
            signature=self.signature(member, body),
        )
        for a, pos, named in attrs:
            if a != "Route" or not pos:
                continue
            methods = (
                [v.upper() for v in (self.string_value(d) for d in self.descendants(named["methods"])) if v]
                if "methods" in named
                else ["ANY"]
            )
            for m in methods:
                self.add_route(
                    m,
                    pos[0],
                    member,
                    "symfony",
                    router=cls.name,
                    handler=sym.qualname,
                    full_path=_join_path(prefix, pos[0]),
                )
        relation: FieldDef | None = None
        if body is not None:
            for d in self.descendants(body, limit=400):
                if d.type == "member_call_expression":
                    mn = self.text(d.child_by_field_name("name"))
                    if mn in _ELOQUENT_RELATIONS:
                        args = self.args(d)
                        target = None
                        if args and args[0].type == "class_constant_access_expression":
                            target = self.text(args[0].named_children[0]).rsplit("\\", 1)[-1]
                        elif args:
                            target = (self.string_value(args[0]) or "").rsplit("\\", 1)[-1] or None
                        relation = FieldDef(
                            name=name,
                            relation=target,
                            attributes=[mn] + (["fk"] if mn == "belongsTo" else []),
                        )
                        break
        self.visit_body(body, sym.qualname)
        return relation

    def function(self, node: Node, cls: SymbolDef | None) -> None:
        name_n = node.child_by_field_name("name")
        body = node.child_by_field_name("body")
        if name_n is None or self.fn_depth:
            self.visit_body(node, None)
            return
        sym = self.add_symbol(
            self.text(name_n), "function", node, exported=True, signature=self.signature(node, body)
        )
        _ = cls
        self.visit_body(body, sym.qualname)

    def member_call(self, node: Node) -> None:
        obj = node.child_by_field_name("object")
        name_n = node.child_by_field_name("name")
        base = self.parts(obj)
        if base is not None and name_n is not None:
            self.add_call([*base, self.text(name_n)], node)
        if name_n is not None and self.text(name_n) == "group":
            prefix = self.chain_prefix(obj)
            if prefix is not None:
                self.route_prefix.append(prefix)
                try:
                    self.visit_children(node)
                finally:
                    self.route_prefix.pop()
                return
        self.visit_children(node)

    def chain_prefix(self, node: Node | None) -> str | None:
        while node is not None:
            if node.type == "scoped_call_expression":
                if self.text(node.child_by_field_name("name")) == "prefix":
                    args = self.args(node)
                    return self.string_value(args[0]) if args else None
                return None
            if node.type == "member_call_expression":
                if self.text(node.child_by_field_name("name")) == "prefix":
                    args = self.args(node)
                    return self.string_value(args[0]) if args else None
                node = node.child_by_field_name("object")
                continue
            return None
        return None

    def scoped_call(self, node: Node) -> None:
        scope = node.child_by_field_name("scope")
        name_n = node.child_by_field_name("name")
        sp = self.parts(scope)
        if sp is None or name_n is None:
            self.visit_children(node)
            return
        cls, meth = sp[-1], self.text(name_n)
        self.add_call([cls, meth], node)
        args = self.args(node)
        if cls == "Route":
            self.laravel_route(node, meth, args)
        elif meth in ("dispatch", "dispatchSync", "dispatchNow") and cls not in _PHP_FACADES:
            self.fa.publishes.append(
                PublishRef(caller=self.caller(), task=cls, technology="laravel_queue", line=self.line(node))
            )
        self.visit_children(node)

    def laravel_handler(self, node: Node | None) -> list[str] | None:
        if node is None:
            return None
        if node.type == "array_creation_expression":
            items = [
                c.named_children[0]
                for c in node.named_children
                if c.type == "array_element_initializer" and c.named_children
            ]
            if len(items) == 2 and items[0].type == "class_constant_access_expression":
                return [
                    self.text(items[0].named_children[0]).rsplit("\\", 1)[-1],
                    self.string_value(items[1]) or "",
                ]
            return None
        if node.type == "class_constant_access_expression":
            return [self.text(node.named_children[0]).rsplit("\\", 1)[-1]]
        s = self.string_value(node)
        if s and "@" in s:
            c, m = s.split("@", 1)
            return [c.rsplit("\\", 1)[-1], m]
        return None

    def laravel_route(self, node: Node, meth: str, args: list[Node]) -> None:
        if meth in _LARAVEL_VERBS and len(args) >= 1:
            path = self.string_value(args[0])
            if path is None:
                return
            ref = self.laravel_handler(args[1]) if len(args) > 1 else None
            self.add_route(
                "ANY" if meth == "any" else meth,
                path,
                node,
                "laravel",
                handler_ref=ref,
                full_path=_join_path(*self.route_prefix, path),
            )
            self.add_app_object("laravel")
        elif meth == "match" and len(args) >= 2:
            path = self.string_value(args[1])
            if path is None:
                return
            verbs = [v.upper() for v in (self.string_value(d) for d in self.descendants(args[0])) if v]
            ref = self.laravel_handler(args[2]) if len(args) > 2 else None
            for v in verbs or ["ANY"]:
                self.add_route(
                    v, path, node, "laravel", handler_ref=ref, full_path=_join_path(*self.route_prefix, path)
                )
        elif meth in ("resource", "apiResource") and len(args) >= 2:
            name = self.string_value(args[0])
            ref = self.laravel_handler(args[1])
            if name is None:
                return
            ctrl = ref[0] if ref else None
            base = _join_path(*self.route_prefix, name)
            for action, verb, member in (
                ("index", "GET", False),
                ("store", "POST", False),
                ("show", "GET", True),
                ("update", "PUT", True),
                ("destroy", "DELETE", True),
            ):
                path = base + ("/{id}" if member else "")
                self.add_route(
                    verb, path, node, "laravel", handler_ref=[ctrl, action] if ctrl else None, full_path=path
                )


# --------------------------------------------------------------------------------------------------- Prisma

_PRISMA_BLOCK_RE: Final = re.compile(
    r"^\s*(model|enum|view|type|datasource|generator)\s+([A-Za-z_]\w*)\s*\{(.*)$"
)
_PRISMA_ATTR_RE: Final = re.compile(r"@[\w.]+(?:\((?:[^()\"]|\"[^\"]*\"|\((?:[^()\"]|\"[^\"]*\")*\))*\))?")


def _strip_prisma_comment(line: str) -> str:
    out: list[str] = []
    in_str = False
    i = 0
    while i < len(line):
        ch = line[i]
        if ch == '"' and (i == 0 or line[i - 1] != "\\"):
            in_str = not in_str
        if not in_str and line.startswith("//", i):
            break
        out.append(ch)
        i += 1
    return "".join(out).strip()


def _analyze_prisma(text: str, fa: FileAnalysis) -> None:
    lines = text.splitlines()
    blocks: list[tuple[str, str, int, int, list[tuple[int, str]]]] = []
    leading: list[str] = []
    seen_code = False
    i = 0
    while i < len(lines):
        raw = lines[i]
        if not seen_code:
            s = raw.strip()
            if s.startswith("//"):
                leading.append(s)
                i += 1
                continue
            if s:
                seen_code = True
        m = _PRISMA_BLOCK_RE.match(_strip_prisma_comment(raw))
        if m is None:
            i += 1
            continue
        kind, name, rest = m.group(1), m.group(2), m.group(3)
        start = i + 1
        body: list[tuple[int, str]] = []
        if "}" in rest:
            body.append((i + 1, rest.split("}", 1)[0]))
            blocks.append((kind, name, start, i + 1, body))
            i += 1
            continue
        j = i + 1
        while j < len(lines):
            s = _strip_prisma_comment(lines[j])
            if s.startswith("}"):
                break
            if s:
                body.append((j + 1, s))
            j += 1
        if j >= len(lines):
            fa.errors.append(f"prisma: unterminated {kind} block '{name}' at line {start}")
        blocks.append((kind, name, start, min(j + 1, len(lines)), body))
        i = j + 1
    if leading:
        fa.docstring = _clean_comment("\n".join(leading))
    model_names = {b[1] for b in blocks if b[0] in ("model", "view", "type")}
    for kind, name, start, end, body in blocks:
        if kind == "enum":
            values = [FieldDef(name=s.split()[0]) for _ln, s in body if s and not s.startswith("@")]
            fa.schemas.append(
                SchemaDef(name=name, schema_kind="prisma_enum", start_line=start, end_line=end, fields=values)
            )
            continue
        if kind == "datasource":
            provider = None
            for _ln, s in body:
                pm = re.match(r'provider\s*=\s*"([^"]+)"', s)
                if pm is not None:
                    provider = pm.group(1)
            fa.infra.append(
                InfraDef(
                    resource_kind="prisma_datasource",
                    name=name,
                    provider=provider,
                    start_line=start,
                    end_line=end,
                )
            )
            continue
        if kind == "generator":
            continue
        fields: list[FieldDef] = []
        table: str | None = None
        fk_names: set[str] = set()
        compound_ids: set[str] = set()
        for _ln, s in body:
            if s.startswith("@@"):
                mm = re.match(r'@@map\(\s*(?:name\s*:\s*)?"([^"]+)"', s)
                if mm is not None:
                    table = mm.group(1)
                im = re.match(r"@@id\(\s*(?:fields\s*:\s*)?\[([^\]]*)\]", s)
                if im is not None:
                    compound_ids |= {x.strip() for x in im.group(1).split(",") if x.strip()}
                continue
            fm = re.match(r"^([A-Za-z_]\w*)\s+([A-Za-z_][\w.]*(?:\([^)]*\))?(?:\[\])?\??)(.*)$", s)
            if fm is None:
                continue
            fname, ftype, rest = fm.group(1), fm.group(2), fm.group(3)
            base = re.sub(r"(\[\]|\?)+$", "", ftype)
            attrs: list[str] = []
            if ftype.endswith("?"):
                attrs.append("nullable")
            if ftype.endswith("[]"):
                attrs.append("list")
            for attr in _PRISMA_ATTR_RE.findall(rest):
                an = attr[1:].split("(", 1)[0]
                if an == "id":
                    attrs.append("primary_key")
                elif an == "unique":
                    attrs.append("unique")
                elif an == "default":
                    attrs.append("default")
                elif an == "updatedAt":
                    attrs.append("updated_at")
                elif an == "relation":
                    attrs.append("relation")
                    fk = re.search(r"fields\s*:\s*\[([^\]]*)\]", attr)
                    if fk is not None:
                        fk_names |= {x.strip() for x in fk.group(1).split(",") if x.strip()}
                elif an.startswith("db."):
                    attrs.append(an)
            fields.append(
                FieldDef(
                    name=fname, type=ftype, relation=base if base in model_names else None, attributes=attrs
                )
            )
        for f in fields:
            if f.name in fk_names and "fk" not in f.attributes:
                f.attributes.append("fk")
            if f.name in compound_ids and "primary_key" not in f.attributes:
                f.attributes.append("primary_key")
        fa.schemas.append(
            SchemaDef(
                name=name, schema_kind="prisma", start_line=start, end_line=end, fields=fields, table=table
            )
        )


