class _RepoIndex:
    """Lookup helpers over the repository's file paths (resolution of relative / package imports)."""

    def __init__(self, paths: Iterable[str]) -> None:
        self.paths: frozenset[str] = frozenset(p for p in paths if isinstance(p, str))
        dirs: set[str] = set()
        by_name: dict[str, list[str]] = {}
        for p in self.paths:
            by_name.setdefault(p.rsplit("/", 1)[-1].lower(), []).append(p)
            parts = p.split("/")[:-1]
            for i in range(1, len(parts) + 1):
                dirs.add("/".join(parts[:i]))
        self.dirs: frozenset[str] = frozenset(dirs)
        self._by_name = {k: sorted(v, key=lambda s: (s.count("/"), s)) for k, v in by_name.items()}
        by_last_dir: dict[str, list[str]] = {}
        for d in self.dirs:
            by_last_dir.setdefault(d.rsplit("/", 1)[-1].lower(), []).append(d)
        self._by_last_dir = {k: sorted(v, key=lambda s: (s.count("/"), s)) for k, v in by_last_dir.items()}
        self._lock = threading.Lock()
        self._suffix_cache: dict[tuple[str, bool], str | None] = {}

    def has(self, path: str) -> bool:
        return path in self.paths

    def file_with_suffix(self, suffix: str, *, ignore_case: bool = False) -> str | None:
        """Shortest repository path equal to / ending with `/suffix`."""
        key = (suffix, ignore_case)
        with self._lock:
            if key in self._suffix_cache:
                return self._suffix_cache[key]
        name = suffix.rsplit("/", 1)[-1].lower()
        want = suffix.lower() if ignore_case else suffix
        found: str | None = None
        for cand in self._by_name.get(name, ()):
            c = cand.lower() if ignore_case else cand
            if c == want or c.endswith("/" + want):
                found = cand
                break
        with self._lock:
            self._suffix_cache[key] = found
        return found

    def dir_with_suffix(self, suffix: str) -> str | None:
        name = suffix.rsplit("/", 1)[-1].lower()
        for cand in self._by_last_dir.get(name, ()):
            if cand == suffix or cand.endswith("/" + suffix):
                return cand
        return None

    def dir_has_ext(self, directory: str, ext: str) -> bool:
        prefix = directory + "/" if directory else ""
        return any(p.startswith(prefix) and "/" not in p[len(prefix) :] for p in self._by_ext_cache(ext))

    @lru_cache(maxsize=16)  # noqa: B019 - bounded, index objects are few and long-lived per analysis run
    def _by_ext_cache(self, ext: str) -> tuple[str, ...]:
        return tuple(p for p in self.paths if p.endswith(ext))


