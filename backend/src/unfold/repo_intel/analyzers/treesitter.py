class _KotlinExtractor(_JvmMixin):
    def parts(self, node: Node | None) -> list[str] | None:
        if node is None:
            return None
        t = node.type
        if t in ("simple_identifier", "type_identifier"):
            return [self.text(node)]
        if t == "this_expression":
            return ["this"]
        if t == "super_expression":
            return ["super"]
        if t == "navigation_expression":
            kids = node.named_children
            if len(kids) != 2 or kids[1].type != "navigation_suffix":
                return None
            base = self.parts(kids[0])
            ident = next((c for c in kids[1].named_children if c.type == "simple_identifier"), None)
            return [*base, self.text(ident)] if base is not None and ident is not None else None
        if t == "parenthesized_expression":
            inner = node.named_children
            return self.parts(inner[0]) if inner else None
        return None

    def annotations(self, node: Node) -> list[tuple[str, list[Node], dict[str, Node]]]:
        mods = next((c for c in node.named_children if c.type == "modifiers"), None)
        out: list[tuple[str, list[Node], dict[str, Node]]] = []
        if mods is None:
            return out
        for ann in mods.named_children:
            if ann.type != "annotation":
                continue
            inv = next((c for c in ann.named_children if c.type == "constructor_invocation"), None)
            user = next((c for c in (inv or ann).named_children if c.type == "user_type"), None)
            if user is None:
                continue
            name = self.text(user).rsplit(".", 1)[-1]
            positional: list[Node] = []
            named: dict[str, Node] = {}
            vargs = (
                next((c for c in inv.named_children if c.type == "value_arguments"), None) if inv else None
            )
            for va in vargs.named_children if vargs is not None else []:
                if va.type != "value_argument":
                    continue
                kids = va.named_children
                if len(kids) >= 2 and kids[0].type == "simple_identifier":
                    named[self.text(kids[0])] = kids[-1]
                elif kids:
                    positional.append(kids[-1])
            out.append((name, positional, named))
        return out

    def kt_strings(self, node: Node | None) -> list[str]:
        if node is None:
            return []
        s = self.string_value(node)
        if s is not None:
            return [s]
        if node.type in ("collection_literal", "call_expression"):
            return [v for v in (self.string_value(d) for d in self.descendants(node)) if v is not None]
        return []

    def ann_info(self, node: Node) -> tuple[dict[str, list[str]], dict[str, list[str]], list[str]]:
        info: dict[str, list[str]] = {}
        methods: dict[str, list[str]] = {}
        names: list[str] = []
        for name, positional, named in self.annotations(node):
            names.append(name)
            values: list[str] = []
            for p in positional[:1]:
                values += self.kt_strings(p)
            for key in ("value", "path", "topics", "queues", "cron"):
                values += self.kt_strings(named.get(key))
            if "method" in named:
                methods[name] = [
                    self.text(d).rsplit(".", 1)[-1].upper()
                    for d in self.descendants(named["method"])
                    if d.type == "simple_identifier" and self.text(d).isupper()
                ]
            info[name] = values
        return info, methods, names

    def visibility(self, node: Node) -> set[str]:
        mods = next((c for c in node.named_children if c.type == "modifiers"), None)
        if mods is None:
            return set()
        return {
            self.text(c)
            for c in mods.named_children
            if c.type in ("visibility_modifier", "function_modifier")
        }

    def visit(self, node: Node) -> None:
        t = node.type
        if t == "import_header":
            ident = next((c for c in node.named_children if c.type == "identifier"), None)
            if ident is not None:
                alias_n = next((c for c in node.named_children if c.type == "import_alias"), None)
                alias = None
                if alias_n is not None:
                    a = next(
                        (
                            c
                            for c in alias_n.named_children
                            if c.type in ("type_identifier", "simple_identifier")
                        ),
                        None,
                    )
                    alias = self.text(a) if a is not None else None
                wildcard = any(c.type == "wildcard_import" for c in node.named_children)
                self.jvm_import(node, self.text(ident), wildcard=wildcard, alias=alias, static=False)
        elif t in ("class_declaration", "object_declaration"):
            self.type_decl(node)
        elif t == "function_declaration":
            self.function(node, None, None, "")
        elif t == "call_expression":
            self.call(node)
        else:
            self.visit_children(node)

    def call(self, node: Node) -> None:
        kids = node.named_children
        if not kids:
            return
        callee = kids[0]
        p = self.parts(callee)
        suffix = next((c for c in kids if c.type == "call_suffix"), None)
        if p:
            self.add_call(p, node)
            if len(p) == 1 and suffix is not None and "io.ktor" in " ".join(self.imported_packages()):
                self.ktor_route(node, p[0], suffix)
                return
        self.visit_children(node)

    def ktor_route(self, node: Node, name: str, suffix: Node) -> None:
        vargs = next((c for c in suffix.named_children if c.type == "value_arguments"), None)
        first: str | None = None
        if vargs is not None:
            va = next((c for c in vargs.named_children if c.type == "value_argument"), None)
            if va is not None and va.named_children:
                first = self.string_value(va.named_children[-1])
        prefixes: list[str] = getattr(self, "_ktor_prefix", [])
        if name == "route" and first is not None:
            prefixes.append(first)
            self._ktor_prefix = prefixes
            try:
                self.visit_children(node)
            finally:
                prefixes.pop()
            return
        if name in _HTTP_METHODS and first is not None and first.startswith("/"):
            self.add_route(name, first, node, "ktor", handler=None, full_path=_join_path(*prefixes, first))
            self.add_app_object("ktor")
        self.visit_children(node)

    def type_decl(self, node: Node) -> None:
        name_n = next(
            (c for c in node.named_children if c.type in ("type_identifier", "simple_identifier")), None
        )
        if name_n is None or self.fn_depth:
            self.visit_body(node, None)
            return
        name = self.text(name_n)
        is_interface = any(c.type == "interface" for c in node.children)
        kind: SymbolKind = "interface" if is_interface else "class"
        bases: list[str] = []
        for c in node.named_children:
            if c.type in ("delegation_specifier", "delegation_specifiers"):
                for u in self.descendants(c):
                    if u.type == "user_type":
                        bases.append(self.text(u))
                        break
        anns, _methods, ann_names = self.ann_info(node)
        vis = self.visibility(node)
        body = next((c for c in node.named_children if c.type in ("class_body", "enum_class_body")), None)
        sym = self.add_symbol(
            name,
            kind,
            node,
            decorators=ann_names,
            bases=bases,
            exported=not ({"private", "internal"} & vis),
            signature=self.signature(node, body),
        )
        prefix, framework = self.class_routes(name, anns, node)
        entity = "Entity" in anns or "Document" in anns
        fields: list[FieldDef] = []
        if entity:
            ctor = next((c for c in node.named_children if c.type == "primary_constructor"), None)
            for param in (c for c in (ctor.named_children if ctor else []) if c.type == "class_parameter"):
                pn = next((c for c in param.named_children if c.type == "simple_identifier"), None)
                pt = next((c for c in param.named_children if c.type in ("user_type", "nullable_type")), None)
                if pn is None:
                    continue
                p_anns, _pm, p_names = self.ann_info(param)
                attrs = ["primary_key"] if "Id" in p_anns else []
                relation = (
                    self.text(pt).rstrip("?") if pt is not None and _JPA_RELATIONS & set(p_names) else None
                )
                fields.append(
                    FieldDef(
                        name=self.text(pn), type=self.text(pt) or None, relation=relation, attributes=attrs
                    )
                )
        self.containers.append(sym.qualname)
        self.scope.append(sym.qualname)
        try:
            for member in body.named_children if body is not None else []:
                if member.type == "function_declaration":
                    self.function(member, sym, prefix, framework)
                elif member.type in ("class_declaration", "object_declaration"):
                    self.type_decl(member)
                elif member.type == "companion_object":
                    inner = next((c for c in member.named_children if c.type == "class_body"), None)
                    for m in inner.named_children if inner is not None else []:
                        if m.type == "function_declaration":
                            self.function(m, sym, prefix, framework)
                        else:
                            self.visit(m)
                else:
                    self.visit(member)
        finally:
            self.containers.pop()
            self.scope.pop()
        if entity:
            self.fa.schemas.append(
                SchemaDef(
                    name=name,
                    schema_kind="orm_model",
                    start_line=self.line(node),
                    end_line=self.end_line(node),
                    fields=fields,
                    symbol=sym.qualname,
                )
            )

    def function(self, node: Node, cls: SymbolDef | None, prefix: str | None, framework: str) -> None:
        name_n = next((c for c in node.named_children if c.type == "simple_identifier"), None)
        body = next((c for c in node.named_children if c.type == "function_body"), None)
        if name_n is None or self.fn_depth:
            self.visit_body(node, None)
            return
        anns, methods_of, ann_names = self.ann_info(node)
        vis = self.visibility(node)
        sym = self.add_symbol(
            self.text(name_n),
            "method" if cls is not None else "function",
            node,
            parent=cls.qualname if cls is not None else None,
            decorators=ann_names,
            exported=not ({"private", "internal"} & vis),
            is_async="suspend" in vis,
            signature=self.signature(node, body),
        )
        if cls is not None:
            self.method_routes(cls.name, sym.qualname, anns, methods_of, prefix, framework, node)
        self.method_tasks(sym.qualname, anns, node)
        self.visit_body(body, sym.qualname)


