def _join_path(*parts: str | None) -> str:
    segs = [p.strip("/") for p in parts if p and p.strip("/")]
    return "/" + "/".join(segs)


def _clean_comment(raw: str) -> str | None:
    out: list[str] = []
    for line in raw.splitlines():
        s = line.strip()
        for prefix in ("/**", "/*!", "/*", "*/", "///", "//!", "//", "#", "*"):
            if s.startswith(prefix):
                s = s[len(prefix) :]
                break
        if s.endswith("*/"):
            s = s[:-2]
        s = s.strip()
        if _PRAGMA_RE.match(s):
            continue
        out.append(s)
    while out and not out[0]:
        out.pop(0)
    while out and not out[-1]:
        out.pop()
    text = "\n".join(out).strip()
    if not text:
        return None
    return text[:_MAX_DOC_CHARS]


def _is_pascal(name: str) -> bool:
    return bool(name) and name[0].isupper() and not name.isupper()


def _lower_first(name: str) -> str:
    return name[:1].lower() + name[1:]


def _singularize(word: str) -> str:
    if word.endswith("ies") and len(word) > 3:
        return word[:-3] + "y"
    if word.endswith(("ses", "xes", "zes", "ches", "shes")):
        return word[:-2]
    if word.endswith("s") and not word.endswith("ss"):
        return word[:-1]
    return word


def _camelize(word: str) -> str:
    return "::".join("".join(p[:1].upper() + p[1:] for p in seg.split("_")) for seg in word.split("/"))


def _syntax_error_lines(root: Node, limit: int = 5) -> list[int]:
    lines: list[int] = []
    stack = [root]
    while stack and len(lines) < limit:
        n = stack.pop()
        if n.type == "ERROR" or n.is_missing:
            line = n.start_point.row + 1
            if line not in lines:
                lines.append(line)
            continue
        if n.has_error:
            stack.extend(reversed(n.children))
    return sorted(lines)


def _npm_package(spec: str) -> str:
    segs = spec.split("/")
    if spec.startswith("@") and len(segs) >= 2:
        return "/".join(segs[:2])
    return segs[0]


def _go_package(path: str) -> str:
    segs = path.split("/")
    if "." not in segs[0]:
        return segs[0]
    if (
        segs[0] in {"github.com", "gitlab.com", "bitbucket.org", "golang.org", "codeberg.org"}
        and len(segs) >= 3
    ):
        return "/".join(segs[:3])
    return "/".join(segs[:2])


def _go_local_name(path: str) -> str:
    segs = [s for s in path.split("/") if s]
    if not segs:
        return path
    last = segs[-1]
    if re.fullmatch(r"v\d+", last) and len(segs) > 1:
        last = segs[-2]
    last = re.sub(r"\.v\d+$", "", last)
    for prefix in ("go-",):
        if last.startswith(prefix) and len(last) > len(prefix):
            last = last[len(prefix) :]
    return last.replace("-", "_").replace(".", "_")


