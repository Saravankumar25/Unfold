_thread_state = threading.local()


@lru_cache(maxsize=1)
def _installed_grammars() -> frozenset[str]:
    """Grammars usable without a network download (the language pack fetches missing ones lazily)."""
    try:
        return frozenset(tslp.available_languages()) | frozenset(tslp.downloaded_languages())
    except Exception:  # pragma: no cover - broken native install
        return frozenset()


def _parser_for(grammar: str) -> Parser:
    """Per-thread parser cache (`tree_sitter.Parser` is not thread-safe)."""
    cache: dict[str, Parser] | None = getattr(_thread_state, "parsers", None)
    if cache is None:
        cache = {}
        _thread_state.parsers = cache
    parser = cache.get(grammar)
    if parser is None:
        parser = tslp.get_parser(grammar)
        cache[grammar] = parser
    return parser


