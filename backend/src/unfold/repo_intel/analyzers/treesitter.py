_EXTRACTORS: Final[dict[str, type[_Extractor]]] = {
    "javascript": _JsExtractor,
    "typescript": _JsExtractor,
    "tsx": _JsExtractor,
    "java": _JavaExtractor,
    "kotlin": _KotlinExtractor,
    "go": _GoExtractor,
    "rust": _RustExtractor,
    "csharp": _CSharpExtractor,
    "ruby": _RubyExtractor,
    "php": _PhpExtractor,
}


class TreeSitterAnalyzer:
    """`LanguageAnalyzer` for JS/TS/TSX/JSX, Java, Kotlin, Go, Rust, C#, Ruby, PHP and Prisma schemas.

    `ctx` is optional and duck-typed: when it exposes `repo_paths` (a collection of repository-relative paths)
    or `inventory` (an `Inventory`), relative / package imports are resolved to repository files; an optional
    `path_aliases` mapping (`{"@/": ["src/"]}`, e.g. from tsconfig `paths`) is honoured for JS/TS.
    """

    name: str = "treesitter"

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._index_key: object | None = None
        self._index: _RepoIndex | None = None

    def supports(self, file: InventoryFile) -> bool:
        if not file.is_text or file.oversized:
            return False
        return file.ext.lower() in SUPPORTED_EXTENSIONS

    def analyze(self, file: InventoryFile, text: str, ctx: object | None = None) -> FileAnalysis:
        grammar = _grammar_for(file)
        language = file.language or ("prisma" if _is_prisma(file) else _GRAMMAR_LANGUAGE.get(grammar or ""))
        fa = FileAnalysis(path=file.path, language=language, analyzer=self.name)
        try:
            if _is_prisma(file):
                _analyze_prisma(text, fa)
                return fa
            if grammar is None:
                fa.errors.append(f"treesitter: unsupported file extension '.{file.ext}'")
                return fa
            src = text.encode("utf-8", "replace")
            if len(src) > _MAX_SOURCE_BYTES:
                fa.errors.append(f"treesitter: file larger than {_MAX_SOURCE_BYTES} bytes was not parsed")
                return fa
            if grammar not in _installed_grammars():
                fa.errors.append(f"treesitter: grammar '{grammar}' is not installed; structure not extracted")
                return fa
            tree = _parser_for(grammar).parse(src)
            root = tree.root_node
            if root.has_error:
                lines = _syntax_error_lines(root)
                fa.errors.append(
                    "treesitter: syntax errors near line(s) " + ", ".join(str(n) for n in lines)
                    if lines
                    else "treesitter: syntax errors"
                )
            extractor = _EXTRACTORS[grammar](
                file, src, fa, self._repo_index(ctx), self._aliases(ctx), grammar
            )
            extractor.run(root)
        except Exception as exc:  # the analyzer contract: never raise, record and degrade
            _log.warning("treesitter_analysis_failed", path=file.path, error=type(exc).__name__)
            fa.errors.append(f"treesitter: analysis failed ({type(exc).__name__}: {str(exc)[:200]})")
        return fa

    # ---- ctx helpers

    def _repo_index(self, ctx: object | None) -> _RepoIndex | None:
        if ctx is None:
            return None
        raw: object | None = getattr(ctx, "repo_paths", None)
        if raw is None:
            inventory = getattr(ctx, "inventory", None)
            raw = inventory if getattr(inventory, "files", None) is not None else None
        if raw is None:
            return None
        with self._lock:
            if self._index_key is raw and self._index is not None:
                return self._index
        if isinstance(raw, str):
            return None
        files = getattr(raw, "files", None)
        if files is not None:
            paths: Iterable[str] = [f.path for f in files if isinstance(getattr(f, "path", None), str)]
        elif isinstance(raw, Iterable):
            paths = [p for p in raw if isinstance(p, str)]
        else:
            return None
        index = _RepoIndex(paths)
        with self._lock:
            self._index_key = raw
            self._index = index
        return index

    @staticmethod
    def _aliases(ctx: object | None) -> Mapping[str, Sequence[str]]:
        raw = getattr(ctx, "path_aliases", None) if ctx is not None else None
        if not isinstance(raw, Mapping):
            return {}
        out: dict[str, list[str]] = {}
        for k, v in raw.items():
            if not isinstance(k, str):
                continue
            prefix = k.rstrip("*")
            targets = (
                [v]
                if isinstance(v, str)
                else [t for t in v if isinstance(t, str)]
                if isinstance(v, Sequence)
                else []
            )
            out[prefix] = [t.rstrip("*").rstrip("/") for t in targets]
        return out
