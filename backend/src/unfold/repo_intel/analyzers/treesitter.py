class _GoExtractor(_Extractor):
    def __init__(
        self,
        file: InventoryFile,
        src: bytes,
        fa: FileAnalysis,
        index: _RepoIndex | None,
        aliases: Mapping[str, Sequence[str]],
        grammar: str,
    ) -> None:
        super().__init__(file, src, fa, index, aliases, grammar)
        self.alias_paths: dict[str, str] = {}  # local package name -> import path
        self.router_vars: dict[str, str] = {}
        self.web: str | None = None
        self.struct_names: set[str] = set()
        self.prefixes: list[str] = []
        self.methods_override: dict[int, list[str]] = {}

    def parts(self, node: Node | None) -> list[str] | None:
        if node is None:
            return None
        t = node.type
        if t in ("identifier", "field_identifier", "package_identifier", "type_identifier"):
            return [self.text(node)]
        if t == "selector_expression":
            base = self.parts(node.child_by_field_name("operand"))
            field = node.child_by_field_name("field")
            return [*base, self.text(field)] if base is not None and field is not None else None
        if t == "parenthesized_expression":
            inner = node.named_children
            return self.parts(inner[0]) if inner else None
        return None

    def args(self, call: Node) -> list[Node]:
        a = call.child_by_field_name("arguments")
        return [c for c in a.named_children if c.type not in _COMMENT_TYPES] if a is not None else []

    def prepass(self, root: Node) -> None:
        for c in root.named_children:
            if c.type == "function_declaration":
                n = c.child_by_field_name("name")
                if n is not None:
                    self.local_defs.add(self.text(n))
            elif c.type == "type_declaration":
                for spec in c.named_children:
                    if spec.type == "type_spec":
                        n = spec.child_by_field_name("name")
                        tp = spec.child_by_field_name("type")
                        if n is not None and tp is not None and tp.type == "struct_type":
                            self.struct_names.add(self.text(n))

    def visit(self, node: Node) -> None:
        t = node.type
        if t == "import_spec":
            self.import_spec(node)
        elif t == "function_declaration":
            self.func(node, receiver=None)
        elif t == "method_declaration":
            recv = node.child_by_field_name("receiver")
            rtype = None
            if recv is not None:
                for d in self.descendants(recv):
                    if d.type == "type_identifier":
                        rtype = self.text(d)
                        break
            self.func(node, receiver=rtype)
        elif t == "type_spec":
            self.type_spec(node)
        elif t in ("short_var_declaration", "assignment_statement", "var_spec"):
            self.assign(node)
        elif t == "call_expression":
            self.call(node)
        else:
            self.visit_children(node)

    def import_spec(self, node: Node) -> None:
        path = self.string_value(node.child_by_field_name("path"))
        if path is None:
            return
        name_n = node.child_by_field_name("name")
        alias = self.text(name_n) if name_n is not None else None
        resolved_dir: str | None = None
        segs = path.split("/")
        if self.index is not None and "." in segs[0]:
            for i in range(1, len(segs)):
                suffix = "/".join(segs[i:])
                cand = self.index.dir_with_suffix(suffix)
                if cand is not None and self.index.dir_has_ext(cand, ".go"):
                    resolved_dir = cand
                    break
        external = resolved_dir is None
        self.add_import(
            path,
            node,
            alias=alias,
            resolved_dir=resolved_dir,
            external=external,
            package=_go_package(path) if external else None,
        )
        local = alias if alias not in (None, "_", ".") else _go_local_name(path)
        if alias in ("_", "."):
            return
        assert local is not None
        self.alias_paths[local] = path
        if external:
            self.bind(local, Binding(kind="module", external=path))
        else:
            self.bind(local, Binding(kind="module", path=resolved_dir))
        for prefix, fw in _GO_WEB:
            if path == prefix or path.startswith(prefix + "/"):
                if self.web is None or self.web == "nethttp":
                    self.web = fw
                break

    def framework_of(self, pkg_alias: str) -> str | None:
        path = self.alias_paths.get(pkg_alias)
        if path is None:
            return None
        for prefix, fw in _GO_WEB:
            if path == prefix or path.startswith(prefix + "/"):
                return fw
        return None

    def func(self, node: Node, receiver: str | None) -> None:
        name_n = node.child_by_field_name("name")
        body = node.child_by_field_name("body")
        if name_n is None:
            self.visit_children(node)
            return
        name = self.text(name_n)
        if receiver:
            self.containers.append(receiver)
        try:
            sym = self.add_symbol(
                name,
                "method" if receiver else "function",
                node,
                parent=receiver,
                exported=name[:1].isupper(),
                signature=self.signature(node, body),
            )
        finally:
            if receiver:
                self.containers.pop()
        self.visit_body(body, sym.qualname)

    def type_spec(self, node: Node) -> None:
        name_n = node.child_by_field_name("name")
        tp = node.child_by_field_name("type")
        if name_n is None or tp is None or self.fn_depth:
            self.visit_children(node)
            return
        if tp.type not in ("struct_type", "interface_type"):
            return
        name = self.text(name_n)
        outer = node.parent if node.parent is not None and node.parent.type == "type_declaration" else node
        if outer is not node and len([c for c in outer.named_children if c.type == "type_spec"]) > 1:
            outer = node
        sym = self.add_symbol(
            name,
            "interface" if tp.type == "interface_type" else "class",
            node,
            outer=outer,
            exported=name[:1].isupper(),
        )
        if tp.type == "struct_type":
            self.struct_schema(name, tp, node, outer, sym.qualname)

    def struct_schema(self, name: str, tp: Node, node: Node, outer: Node, qual: str) -> None:
        fields: list[FieldDef] = []
        is_model = False
        flist = next((c for c in tp.named_children if c.type == "field_declaration_list"), None)
        for fd in flist.named_children if flist is not None else []:
            if fd.type != "field_declaration":
                continue
            names = [self.text(n) for n in fd.children_by_field_name("name")]
            type_n = fd.child_by_field_name("type")
            type_text = self.text(type_n) if type_n is not None else None
            tag_n = fd.child_by_field_name("tag")
            tag = self.string_value(tag_n) if tag_n is not None else None
            tags = dict(re.findall(r'(\w+):"([^"]*)"', tag or ""))
            if not names:
                if type_text in ("gorm.Model", "bun.BaseModel", "orm.Model"):
                    is_model = True
                continue
            if _GO_TAG_KEYS & tags.keys():
                is_model = True
            attrs: list[str] = []
            gorm = tags.get("gorm", "").lower()
            db = tags.get("db", "") or tags.get("bun", "")
            if (
                "primarykey" in gorm
                or "primary_key" in gorm
                or "pk" in db.split(",")
                or tags.get("bson") == "_id"
            ):
                attrs.append("primary_key")
            if "unique" in gorm or "unique" in db:
                attrs.append("unique")
            if "not null" in gorm or "notnull" in db:
                attrs.append("not_null")
            if "foreignkey" in gorm:
                attrs.append("fk")
            base = re.sub(r"^[\[\]*]+", "", type_text or "")
            relation = base if base in self.struct_names and base != name else None
            for n in names:
                fields.append(FieldDef(name=n, type=type_text, relation=relation, attributes=list(attrs)))
        if is_model:
            table: str | None = None
            self.fa.schemas.append(
                SchemaDef(
                    name=name,
                    schema_kind="orm_model",
                    start_line=self.line(outer),
                    end_line=self.end_line(node),
                    fields=fields,
                    symbol=qual,
                    table=table,
                )
            )

    def assign(self, node: Node) -> None:
        left = node.child_by_field_name("left") or node.child_by_field_name("name")
        right = node.child_by_field_name("right") or node.child_by_field_name("value")
        lnames = [
            self.text(c)
            for c in (
                left.named_children
                if left is not None and left.type == "expression_list"
                else [left]
                if left is not None
                else []
            )
            if c.type == "identifier"
        ]
        rvals = (
            right.named_children
            if right is not None and right.type == "expression_list"
            else [right]
            if right is not None
            else []
        )
        if len(lnames) >= 1 and rvals and rvals[0] is not None and rvals[0].type == "call_expression":
            self.track(lnames[0], rvals[0])
        self.visit_children(node)

    def track(self, name: str, call: Node) -> None:
        fn = call.child_by_field_name("function")
        p = self.parts(fn)
        args = self.args(call)
        if p and len(p) == 2:
            fw = self.framework_of(p[0])
            if fw is not None and p[1] in _GO_ROUTER_CTORS.get(fw, ()):
                self.router_vars[name] = fw
                self.add_router(name, fw, call)
                self.add_app_object(fw)
                return
            if p[1] == "Group" and args and p[0] in self.router_vars:
                prefix = self.string_value(args[0])
                if prefix is not None:
                    fw = self.router_vars[p[0]]
                    self.router_vars[name] = fw
                    self.add_router(name, f"{fw}_group", call)
                    self.fa.mounts.append(
                        MountDef(parent=p[0], target=[name], prefix=prefix, line=self.line(call))
                    )
                return
        if p and p[-1] == "Subrouter" and fn is not None:
            operand = fn.child_by_field_name("operand")
            if operand is not None and operand.type == "call_expression":
                ofn = self.parts(operand.child_by_field_name("function"))
                oargs = self.args(operand)
                if ofn and len(ofn) == 2 and ofn[1] == "PathPrefix" and oargs:
                    prefix = self.string_value(oargs[0])
                    if prefix is not None:
                        self.router_vars[name] = self.router_vars.get(ofn[0], "gorilla_mux")
                        self.add_router(name, "gorilla_mux_subrouter", call)
                        self.fa.mounts.append(
                            MountDef(parent=ofn[0], target=[name], prefix=prefix, line=self.line(call))
                        )

    def handler(self, node: Node) -> tuple[str | None, list[str] | None]:
        if node.type == "identifier":
            name = self.text(node)
            return (name, None) if name in self.local_defs else (None, [name])
        if node.type == "call_expression":
            args = self.args(node)
            if len(args) == 1:
                return self.handler(args[0])
            return None, None
        p = self.parts(node)
        return (None, p) if p else (None, None)

    def call(self, node: Node) -> None:
        fn = node.child_by_field_name("function")
        p = self.parts(fn)
        args = self.args(node)
        if p:
            self.add_call(p, node)
            if len(p) >= 2 and self.web is not None:
                self.route(node, fn, p, args)
        self.visit_children(node)

    def route(self, node: Node, fn: Node | None, p: list[str], args: list[Node]) -> None:
        recv, meth = ".".join(p[:-1]), p[-1]
        fw = self.router_vars.get(recv) or self.framework_of(recv) or self.web or "nethttp"
        if meth == "Methods" and fn is not None:
            operand = fn.child_by_field_name("operand")
            if operand is not None and operand.type == "call_expression":
                self.methods_override[operand.start_byte] = [
                    v.upper() for v in (self.string_value(a) for a in args) if v
                ]
            return
        if meth == "Route" and len(args) == 2 and args[1].type == "func_literal":
            prefix = self.string_value(args[0])
            if prefix is not None:
                self.prefixes.append(prefix)
                try:
                    self.visit_children(args[1])
                finally:
                    self.prefixes.pop()
                # the literal is visited again by the caller's visit_children; guard by marking
                self.methods_override[-args[1].start_byte - 1] = []
            return
        if meth == "Mount" and len(args) == 2:
            prefix = self.string_value(args[0])
            target = args[1]
            tp = (
                self.parts(target.child_by_field_name("function"))
                if target.type == "call_expression"
                else self.parts(target)
            )
            if prefix is not None and tp:
                self.fa.mounts.append(
                    MountDef(
                        parent=recv,
                        target=tp,
                        prefix=_join_path(*self.prefixes, prefix) if self.prefixes else prefix,
                        line=self.line(node),
                    )
                )
            return
        if not args:
            return
        first = self.string_value(args[0])
        if first is None:
            return
        method: str | None = None
        path: str | None = None
        if meth.lower() in _GO_VERBS and first.startswith("/") and len(args) >= 2:
            method, path = meth.upper(), first
        elif meth in ("Any", "All") and first.startswith("/") and len(args) >= 2:
            method, path = "ANY", first
        elif meth in ("HandleFunc", "Handle", "HandlerFunc") and len(args) >= 2:
            if first.startswith("/"):
                method, path = "ANY", first
            else:
                m = re.fullmatch(r"([A-Z]+)\s+(/\S*)", first)
                if m is not None:
                    method, path = m.group(1), m.group(2)
                elif len(args) >= 3 and first.isupper():
                    second = self.string_value(args[1])
                    if second is not None and second.startswith("/"):
                        method, path = first, second
        elif meth in ("Method", "Handle", "Add") and len(args) >= 3 and first.isupper():
            second = self.string_value(args[1])
            if second is not None and second.startswith("/"):
                method, path = first, second
        if method is None or path is None:
            return
        methods = self.methods_override.pop(node.start_byte, None) or [method]
        handler, ref = self.handler(args[-1])
        for m_ in methods:
            self.add_route(
                m_,
                path,
                node,
                fw,
                router=recv,
                handler=handler,
                handler_ref=ref,
                full_path=_join_path(*self.prefixes, path) if self.prefixes else None,
            )

    def visit_children(self, node: Node) -> None:
        if self.methods_override.pop(-node.start_byte - 1, None) is not None and node.type == "func_literal":
            return
        super().visit_children(node)


