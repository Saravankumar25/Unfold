"""Tree-sitter analyzer for non-Python source languages (LLD §7, ESD §8.1–§8.2).

`TreeSitterAnalyzer` parses one file with a `tree-sitter-language-pack` grammar and walks the concrete syntax tree
to extract structure (symbols, imports, bindings, call sites) plus framework heuristics:

* routes / routers / mounts — Express, Fastify, Koa, Hono, NestJS, Next.js (App + Pages router), Spring MVC,
  JAX-RS, Kotlin Ktor, Go net/http · chi · gin · echo · fiber · gorilla/mux, Rust axum · actix · rocket,
  ASP.NET (controllers + minimal APIs), Rails / Sinatra, Laravel / Symfony;
* schemas — Prisma (`schema.prisma`, small line parser: tree-sitter has no Prisma grammar), TypeORM / Nest
  Mongoose entities, Mongoose `Schema` + `model()`, Sequelize `define()`, JPA `@Entity`, Go structs with
  db/gorm/bun tags, Diesel / sqlx / SeaORM structs, ActiveRecord and Eloquent models;
* data access — Prisma client, Mongoose / Sequelize model statics, repository objects (TypeORM, Spring Data),
  EF Core `DbSet`s, ActiveRecord, Eloquent;
* AI components (LLM / embedding / vector-store SDKs) and background tasks (BullMQ, Bull, Agenda, node-cron,
  Spring `@Scheduled` / listeners, Sidekiq, ActiveJob, Laravel queues).

The analyzer never executes, imports or evaluates repository code, never downloads grammars at analysis time
(a missing grammar is recorded in `FileAnalysis.errors`) and never raises: any failure degrades to a partial
analysis with an `errors` entry.

Contract notes (additions that stay within `repo_intel.models`):
* a module's default export is recorded as `exports` entry ``"default"`` plus ``bindings["default"]`` pointing
  at the local symbol (`Binding(kind="symbol", path=<this file>, attr=<local name>)`) so cross-file mount /
  handler resolution can follow ``import router from "./routes"``;
* Go package imports bind the local package name to `Binding(kind="module", path=<resolved directory>)`;
* Prisma `datasource` blocks are recorded as `InfraDef(resource_kind="prisma_datasource")`.
"""

