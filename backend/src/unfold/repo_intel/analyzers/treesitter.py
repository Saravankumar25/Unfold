_RUST_DB_DERIVES: Final = frozenset(
    {"Queryable", "Insertable", "Selectable", "AsChangeset", "Identifiable", "FromRow", "DeriveEntityModel"}
)
_RUST_ROUTE_ATTRS: Final = frozenset({"get", "post", "put", "patch", "delete", "head", "options"})


class _RustExtractor(_Extractor):
    def parts(self, node: Node | None) -> list[str] | None:
        if node is None:
            return None
        t = node.type
        if t in (
            "identifier",
            "field_identifier",
            "self",
            "crate",
            "super",
            "type_identifier",
            "metavariable",
        ):
            return [self.text(node)]
        if t in ("scoped_identifier", "scoped_type_identifier"):
            path = node.child_by_field_name("path")
            name = node.child_by_field_name("name")
            base = self.parts(path) if path is not None else []
            return [*base, self.text(name)] if base is not None and name is not None else None
        if t == "field_expression":
            base = self.parts(node.child_by_field_name("value"))
            field = node.child_by_field_name("field")
            return [*base, self.text(field)] if base is not None and field is not None else None
        if t == "generic_function":
            return self.parts(node.child_by_field_name("function"))
        return None

    def attributes_before(self, node: Node) -> list[str]:
        out: list[str] = []
        prev = node.prev_named_sibling
        while prev is not None and prev.type in ("attribute_item", "line_comment", "block_comment"):
            if prev.type == "attribute_item":
                out.insert(0, self.text(prev)[2:-1].strip())
            prev = prev.prev_named_sibling
        return out

    def use_leaves(self, node: Node, prefix: list[str]) -> list[tuple[list[str], str | None]]:
        t = node.type
        if t in ("identifier", "crate", "self", "super", "metavariable"):
            return [([*prefix, self.text(node)], None)]
        if t == "scoped_identifier":
            p = self.parts(node)
            return [([*prefix, *p], None)] if p else []
        if t == "use_as_clause":
            path = node.child_by_field_name("path")
            alias = node.child_by_field_name("alias")
            p = self.parts(path) if path is not None else None
            return [([*prefix, *p], self.text(alias) if alias is not None else None)] if p else []
        if t == "use_wildcard":
            inner = node.named_children
            p = self.parts(inner[0]) if inner else []
            return [([*prefix, *(p or []), "*"], None)]
        if t == "scoped_use_list":
            path = node.child_by_field_name("path")
            lst = node.child_by_field_name("list")
            base = self.parts(path) if path is not None else []
            if base is None or lst is None:
                return []
            return self.use_leaves(lst, [*prefix, *base])
        if t == "use_list":
            out: list[tuple[list[str], str | None]] = []
            for c in node.named_children:
                out += self.use_leaves(c, prefix)
            return out
        return []

    def crate_root(self) -> str | None:
        segs = self.file.path.split("/")[:-1]
        for i in range(len(segs) - 1, -1, -1):
            if segs[i] == "src":
                return "/".join(segs[: i + 1])
        return None

    def module_dir(self) -> str:
        d = self.file.directory
        name = self.file.name
        if name in ("mod.rs", "lib.rs", "main.rs"):
            return d
        return posixpath.join(d, name[: -len(".rs")]) if name.endswith(".rs") else d

    def resolve_use(self, segs: list[str]) -> str | None:
        if self.index is None or not segs:
            return None
        if segs[0] == "crate":
            root = self.crate_root()
            if root is None:
                return None
            base, rest = root, segs[1:]
        elif segs[0] == "self":
            base, rest = self.module_dir(), segs[1:]
        elif segs[0] == "super":
            base = self.module_dir()
            rest = segs
            while rest and rest[0] == "super":
                base = base.rsplit("/", 1)[0] if "/" in base else ""
                rest = rest[1:]
        else:
            return None
        rest = [s for s in rest if s != "*"]
        for i in range(len(rest), 0, -1):
            mod = "/".join(rest[:i])
            for cand in (f"{base}/{mod}.rs", f"{base}/{mod}/mod.rs"):
                if self.index.has(cand):
                    return cand
        return None

    def visit(self, node: Node) -> None:
        t = node.type
        if t == "use_declaration":
            self.use_decl(node)
        elif t == "function_item":
            self.function(node, parent=None)
        elif t in ("struct_item", "enum_item", "union_item", "trait_item"):
            self.type_item(node)
        elif t == "impl_item":
            self.impl(node)
        elif t == "mod_item":
            name = node.child_by_field_name("name")
            body = node.child_by_field_name("body")
            if name is not None and body is not None and not self.fn_depth:
                self.containers.append(self.qual(self.text(name)))
                try:
                    self.visit_children(body)
                finally:
                    self.containers.pop()
        elif t == "call_expression":
            self.call(node)
        else:
            self.visit_children(node)

    def use_decl(self, node: Node) -> None:
        arg = node.child_by_field_name("argument")
        if arg is None:
            return
        for segs, alias in self.use_leaves(arg, []):
            if not segs:
                continue
            module = "::".join(segs[:-1]) if len(segs) > 1 else segs[0]
            name = segs[-1]
            internal = segs[0] in ("crate", "self", "super")
            resolved = self.resolve_use(segs) if internal else None
            first = segs[0]
            self.add_import(
                module,
                node,
                names=[name],
                alias=alias,
                resolved_path=resolved,
                external=not internal,
                package=("std" if first in ("std", "core", "alloc") else first) if not internal else None,
            )
            if name != "*":
                local = alias or name
                if internal:
                    self.bind(local, Binding(kind="symbol", path=resolved, attr=name))
                else:
                    self.bind(local, Binding(kind="symbol", attr=name, external="::".join(segs)))

    def is_pub(self, node: Node) -> bool:
        return any(c.type == "visibility_modifier" for c in node.named_children)

    def function(self, node: Node, parent: str | None) -> None:
        name_n = node.child_by_field_name("name")
        body = node.child_by_field_name("body")
        if name_n is None or self.fn_depth:
            self.visit_body(node, None)
            return
        attrs = self.attributes_before(node)
        mods = next((c for c in node.named_children if c.type == "function_modifiers"), None)
        sym = self.add_symbol(
            self.text(name_n),
            "method" if parent else "function",
            node,
            parent=parent,
            decorators=attrs,
            exported=self.is_pub(node),
            is_async=mods is not None and "async" in self.text(mods),
            signature=self.signature(node, body),
        )
        for a in attrs:
            m = re.fullmatch(r"(?:\w+::)*(\w+)\s*\(\s*\"([^\"]*)\"(.*)\)", a, re.DOTALL)
            if m is not None and m.group(1) in _RUST_ROUTE_ATTRS | {"route"}:
                pkgs = self.imported_packages()
                fw = "rocket" if "rocket" in pkgs else "actix"
                method = m.group(1).upper() if m.group(1) != "route" else "ANY"
                mm = re.search(r'method\s*=\s*"(\w+)"', m.group(3))
                if mm is not None:
                    method = mm.group(1).upper()
                self.add_route(method, m.group(2), node, fw, handler=sym.qualname)
                self.add_app_object(fw)
        self.visit_body(body, sym.qualname)

    def type_item(self, node: Node) -> None:
        name_n = node.child_by_field_name("name")
        if name_n is None or self.fn_depth:
            return
        name = self.text(name_n)
        attrs = self.attributes_before(node)
        kind: SymbolKind = "interface" if node.type == "trait_item" else "class"
        body = node.child_by_field_name("body")
        sym = self.add_symbol(
            name,
            kind,
            node,
            decorators=attrs,
            exported=self.is_pub(node),
            signature=self.signature(node, body),
        )
        if node.type == "trait_item" and body is not None:
            self.containers.append(sym.qualname)
            try:
                for m in body.named_children:
                    if m.type in ("function_item", "function_signature_item"):
                        self.function(
                            m, parent=sym.qualname
                        ) if m.type == "function_item" else self.add_symbol(
                            self.text(m.child_by_field_name("name")),
                            "method",
                            m,
                            parent=sym.qualname,
                            exported=True,
                            signature=self.signature(m, None),
                        )
            finally:
                self.containers.pop()
            return
        derives = set(re.findall(r"\b(\w+)\b", " ".join(a for a in attrs if a.startswith("derive"))))
        if node.type == "struct_item" and (
            derives & _RUST_DB_DERIVES or any(a.startswith(("diesel", "sea_orm")) for a in attrs)
        ):
            table = None
            for a in attrs:
                tm = re.search(r'table_name\s*=\s*"?([\w.:]+)"?', a)
                if tm is not None:
                    table = tm.group(1).rsplit("::", 1)[-1]
            fields: list[FieldDef] = []
            for fd in body.named_children if body is not None else []:
                if fd.type != "field_declaration":
                    continue
                fname = fd.child_by_field_name("name")
                ftype = fd.child_by_field_name("type")
                fattrs = (
                    ["primary_key"] if any("primary_key" in a for a in self.attributes_before(fd)) else []
                )
                if fname is not None:
                    fields.append(
                        FieldDef(name=self.text(fname), type=self.text(ftype) or None, attributes=fattrs)
                    )
            self.fa.schemas.append(
                SchemaDef(
                    name=name,
                    schema_kind="orm_model",
                    start_line=self.line(node),
                    end_line=self.end_line(node),
                    fields=fields,
                    symbol=sym.qualname,
                    table=table,
                )
            )

    def impl(self, node: Node) -> None:
        tp = node.child_by_field_name("type")
        body = node.child_by_field_name("body")
        if tp is None or body is None or self.fn_depth:
            self.visit_children(node)
            return
        tname = re.sub(r"<.*$", "", self.text(tp)).rsplit("::", 1)[-1]
        self.containers.append(tname)
        try:
            for m in body.named_children:
                if m.type == "function_item":
                    self.function(m, parent=tname)
                else:
                    self.visit(m)
        finally:
            self.containers.pop()

    def call(self, node: Node) -> None:
        fn = node.child_by_field_name("function")
        p = self.parts(fn)
        if p:
            self.add_call(p, node)
        if fn is not None and fn.type == "field_expression" and "axum" in self.imported_packages():
            field = self.text(fn.child_by_field_name("field"))
            args_n = node.child_by_field_name("arguments")
            args = (
                [c for c in args_n.named_children if c.type not in _COMMENT_TYPES]
                if args_n is not None
                else []
            )
            if field == "route" and len(args) == 2:
                path = self.string_value(args[0])
                if path is not None:
                    for method, handler in self.method_router(args[1]):
                        hp = self.parts(handler) if handler is not None else None
                        local = hp is not None and len(hp) == 1
                        self.add_route(
                            method,
                            path,
                            node,
                            "axum",
                            handler=hp[0] if local and hp else None,
                            handler_ref=None if local else hp,
                        )
                    self.add_app_object("axum")
            elif field in ("nest", "nest_service") and len(args) == 2:
                prefix = self.string_value(args[0])
                target = args[1]
                tp = (
                    self.parts(target.child_by_field_name("function"))
                    if target.type == "call_expression"
                    else self.parts(target)
                )
                if prefix is not None and tp:
                    self.fa.mounts.append(
                        MountDef(parent=None, target=tp, prefix=prefix, line=self.line(node))
                    )
        self.visit_children(node)

    def method_router(self, node: Node) -> list[tuple[str, Node | None]]:
        """`get(h).post(h2)` / `axum::routing::get(h)` -> [("GET", h), ("POST", h2)]."""
        if node.type != "call_expression":
            return []
        fn = node.child_by_field_name("function")
        args_n = node.child_by_field_name("arguments")
        args = (
            [c for c in args_n.named_children if c.type not in _COMMENT_TYPES] if args_n is not None else []
        )
        if fn is None:
            return []
        if fn.type == "field_expression":
            field = self.text(fn.child_by_field_name("field"))
            value = fn.child_by_field_name("value")
            head = self.method_router(value) if value is not None else []
            if field in _RUST_ROUTE_ATTRS or field == "any":
                return [*head, ("ANY" if field == "any" else field.upper(), args[0] if args else None)]
            return head
        p = self.parts(fn)
        if p and (p[-1] in _RUST_ROUTE_ATTRS or p[-1] == "any"):
            return [("ANY" if p[-1] == "any" else p[-1].upper(), args[0] if args else None)]
        return []


