class _RubyExtractor(_Extractor):
    def __init__(
        self,
        file: InventoryFile,
        src: bytes,
        fa: FileAnalysis,
        index: _RepoIndex | None,
        aliases: Mapping[str, Sequence[str]],
        grammar: str,
    ) -> None:
        super().__init__(file, src, fa, index, aliases, grammar)
        self.is_routes_file = file.path.endswith("config/routes.rb")
        self.route_prefix: list[str] = []
        self.ctrl_modules: list[str] = []
        self.model_stack: list[tuple[str, list[FieldDef]] | None] = []

    def parts(self, node: Node | None) -> list[str] | None:
        if node is None:
            return None
        t = node.type
        if t in ("identifier", "constant", "self", "instance_variable", "class_variable"):
            return [self.text(node)]
        if t == "scope_resolution":
            scope = node.child_by_field_name("scope")
            name = node.child_by_field_name("name")
            base = self.parts(scope) if scope is not None else []
            return [*base, self.text(name)] if base is not None and name is not None else None
        if (
            t == "call"
            and node.child_by_field_name("arguments") is None
            and node.child_by_field_name("block") is None
        ):
            recv = node.child_by_field_name("receiver")
            meth = node.child_by_field_name("method")
            base = self.parts(recv) if recv is not None else []
            return [*base, self.text(meth)] if base is not None and meth is not None else None
        return None

    def args(self, call: Node) -> list[Node]:
        a = call.child_by_field_name("arguments")
        return [c for c in a.named_children if c.type not in _COMMENT_TYPES] if a is not None else []

    def sym_value(self, node: Node | None) -> str | None:
        if node is None:
            return None
        if node.type in ("simple_symbol", "hash_key_symbol"):
            return self.text(node).lstrip(":")
        return self.string_value(node)

    def hash_opts(self, args: list[Node]) -> dict[str, Node]:
        out: dict[str, Node] = {}
        for a in args:
            if a.type == "pair":
                k = a.child_by_field_name("key")
                v = a.child_by_field_name("value")
                key = self.sym_value(k) or self.text(k)
                if v is not None:
                    out[key.rstrip(":")] = v
        return out

    def visit(self, node: Node) -> None:
        t = node.type
        if t in ("class", "module"):
            self.class_or_module(node)
        elif t == "method":
            self.method(node, singleton=False)
        elif t == "singleton_method":
            self.method(node, singleton=True)
        elif t == "call":
            self.call(node)
        else:
            self.visit_children(node)

    def class_or_module(self, node: Node) -> None:
        name_n = node.child_by_field_name("name")
        if name_n is None or self.fn_depth:
            self.visit_children(node)
            return
        name = self.text(name_n).replace("::", ".")
        sup = node.child_by_field_name("superclass")
        bases = [self.text(c) for c in sup.named_children] if sup is not None else []
        qual = self.qual(name)
        model: tuple[str, list[FieldDef]] | None = None
        if node.type == "class":
            sym = self.add_symbol(
                name.rsplit(".", 1)[-1] if "." in name else name,
                "class",
                node,
                bases=bases,
                exported=True,
                signature=self.signature(node, node.child_by_field_name("body")),
            )
            qual = sym.qualname if "." not in name else qual
            if any(b in ("ApplicationRecord", "ActiveRecord::Base") for b in bases):
                model = (name.rsplit(".", 1)[-1], [])
            if any(b in ("ApplicationJob", "ActiveJob::Base") for b in bases):
                self.fa.tasks.append(
                    TaskDef(name=name, technology="activejob", line=self.line(node), symbol=qual)
                )
        self.containers.append(qual)
        self.scope.append(qual)
        self.model_stack.append(model)
        try:
            body = node.child_by_field_name("body")
            if body is not None:
                self.visit_children(body)
        finally:
            self.containers.pop()
            self.scope.pop()
            self.model_stack.pop()
        if model is not None:
            self.fa.schemas.append(
                SchemaDef(
                    name=model[0],
                    schema_kind="orm_model",
                    start_line=self.line(node),
                    end_line=self.end_line(node),
                    fields=model[1],
                    symbol=qual,
                    table=None,
                )
            )

    def method(self, node: Node, *, singleton: bool) -> None:
        name_n = node.child_by_field_name("name")
        if name_n is None or self.fn_depth:
            self.visit_body(node, None)
            return
        in_class = bool(self.containers)
        params = node.child_by_field_name("parameters")
        sym = self.add_symbol(
            self.text(name_n),
            "method" if in_class else "function",
            node,
            parent=self.containers[-1] if in_class else None,
            exported=True,
            signature=self.signature(node, None, None)
            if params is None
            else " ".join(self.src[node.start_byte : params.end_byte].decode("utf-8", "replace").split())[
                :_MAX_SIGNATURE_CHARS
            ],
        )
        _ = singleton
        self.visit_body(node.child_by_field_name("body") or node, sym.qualname)

    def call(self, node: Node) -> None:
        recv = node.child_by_field_name("receiver")
        meth_n = node.child_by_field_name("method")
        if meth_n is None:
            self.visit_children(node)
            return
        meth = self.text(meth_n)
        args = self.args(node)
        if recv is None:
            if meth in ("require", "require_relative", "load", "autoload") and args:
                spec = self.string_value(args[-1] if meth == "autoload" else args[0])
                if spec is not None:
                    self.require(node, spec, relative=meth == "require_relative")
                return
            if self.handle_dsl(node, meth, args):
                return
        base = self.parts(recv) if recv is not None else []
        if base is not None:
            parts = [*base, meth]
            self.add_call(parts, node)
            if len(parts) == 2 and parts[0][:1].isupper():
                if meth in ("perform_async", "perform_in", "perform_at"):
                    self.fa.publishes.append(
                        PublishRef(
                            caller=self.caller(), task=parts[0], technology="sidekiq", line=self.line(node)
                        )
                    )
                elif meth in ("perform_later", "perform_now", "set"):
                    self.fa.publishes.append(
                        PublishRef(
                            caller=self.caller(), task=parts[0], technology="activejob", line=self.line(node)
                        )
                    )
        self.visit_children(node)

    def require(self, node: Node, spec: str, *, relative: bool) -> None:
        resolved: str | None = None
        if self.index is not None:
            if relative:
                base = posixpath.normpath(posixpath.join(self.file.directory, spec))
                for cand in (base, base + ".rb"):
                    if self.index.has(cand):
                        resolved = cand
                        break
            else:
                for cand in (f"lib/{spec}.rb", f"{spec}.rb", f"app/{spec}.rb", f"lib/{spec}"):
                    if self.index.has(cand):
                        resolved = cand
                        break
        external = resolved is None and not relative
        self.add_import(spec, node, resolved_path=resolved, external=external, package=spec.split("/")[0])

    def handle_dsl(self, node: Node, meth: str, args: list[Node]) -> bool:
        """Receiver-less DSL calls: routes, associations, includes. True when fully handled."""
        model = self.model_stack[-1] if self.model_stack else None
        if (
            model is not None
            and meth in ("has_many", "belongs_to", "has_one", "has_and_belongs_to_many")
            and args
        ):
            assoc = self.sym_value(args[0])
            if assoc:
                opts = self.hash_opts(args[1:])
                target = self.string_value(opts.get("class_name")) or _camelize(
                    _singularize(assoc) if meth in ("has_many", "has_and_belongs_to_many") else assoc
                )
                attrs = [meth] + (["fk"] if meth == "belongs_to" else [])
                model[1].append(FieldDef(name=assoc, relation=target, attributes=attrs))
            return True
        if meth == "include" and args and self.containers:
            mod = self.text(args[0])
            if mod in ("Sidekiq::Worker", "Sidekiq::Job"):
                cls = self.containers[-1]
                self.fa.tasks.append(
                    TaskDef(name=cls, technology="sidekiq", line=self.line(node), symbol=cls)
                )
            return False
        framework = (
            "rails" if self.is_routes_file else "sinatra" if "sinatra" in self.imported_packages() else None
        )
        if framework is None:
            return False
        block = node.child_by_field_name("block")
        if framework == "rails" and meth in ("namespace", "scope") and block is not None:
            name = self.sym_value(args[0]) if args else None
            opts = self.hash_opts(args)
            path = self.string_value(opts.get("path")) if "path" in opts else name
            self.route_prefix.append(path or "")
            if meth == "namespace" and name:
                self.ctrl_modules.append(_camelize(name))
            try:
                self.visit_children(block)
            finally:
                self.route_prefix.pop()
                if meth == "namespace" and name:
                    self.ctrl_modules.pop()
            return True
        if framework == "rails" and meth in ("resources", "resource") and args:
            name = self.sym_value(args[0])
            if not name:
                return False
            opts = self.hash_opts(args[1:])
            only: set[str] | None = None
            if "only" in opts:
                only = {v for v in (self.sym_value(c) for c in self.descendants(opts["only"])) if v}
            except_: set[str] = set()
            if "except" in opts:
                except_ = {v for v in (self.sym_value(c) for c in self.descendants(opts["except"])) if v}
            ctrl = "::".join([*self.ctrl_modules, _camelize(name) + "Controller"])
            base = _join_path(*self.route_prefix, name)
            for action, verb, member in _RAILS_RESOURCE_ACTIONS:
                if (only is not None and action not in only) or action in except_:
                    continue
                if meth == "resource" and action == "index":
                    continue
                path = base + ("/:id" if member and meth == "resources" else "")
                self.add_route(verb, path, node, "rails", handler_ref=[ctrl, action], full_path=path)
            if block is not None:
                self.route_prefix.append(f"{name}/:{_singularize(name)}_id" if meth == "resources" else name)
                try:
                    self.visit_children(block)
                finally:
                    self.route_prefix.pop()
            return True
        if framework == "rails" and meth == "root" and args:
            to = self.string_value(args[0]) or self.string_value(self.hash_opts(args).get("to"))
            if to and "#" in to:
                c, a = to.split("#", 1)
                self.add_route(
                    "GET", "/", node, "rails", handler_ref=[_camelize(c) + "Controller", a], full_path="/"
                )
            return True
        if meth in _RAILS_VERBS and args:
            path = self.string_value(args[0])
            to = None
            if path is None and args[0].type == "pair":
                path = self.string_value(args[0].child_by_field_name("key"))
                to = self.string_value(args[0].child_by_field_name("value"))
            if path is None:
                return False
            opts = self.hash_opts(args[1:])
            to = to or self.string_value(opts.get("to"))
            ref: list[str] | None = None
            if to and "#" in to:
                c, a = to.split("#", 1)
                ref = ["::".join([*self.ctrl_modules, _camelize(c) + "Controller"]), a]
            verbs = (
                [meth.upper()]
                if meth != "match"
                else [v.upper() for v in (self.sym_value(c) for c in self.descendants(opts["via"])) if v]
                if "via" in opts
                else ["ANY"]
            )
            full = _join_path(*self.route_prefix, path)
            for v in verbs or ["ANY"]:
                self.add_route(v, path, node, framework, handler_ref=ref, full_path=full)
            if framework == "sinatra":
                self.add_app_object("sinatra")
                block_n = node.child_by_field_name("block")
                self.visit_body(block_n, None)
            return True
        return False


