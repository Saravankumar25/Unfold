class _CSharpExtractor(_Extractor):
    def __init__(
        self,
        file: InventoryFile,
        src: bytes,
        fa: FileAnalysis,
        index: _RepoIndex | None,
        aliases: Mapping[str, Sequence[str]],
        grammar: str,
    ) -> None:
        super().__init__(file, src, fa, index, aliases, grammar)
        self.namespace_root: str | None = None

    def parts(self, node: Node | None) -> list[str] | None:
        if node is None:
            return None
        t = node.type
        if t == "identifier":
            return [self.text(node)]
        if t in ("this_expression", "this"):
            return ["this"]
        if t in ("base_expression", "base"):
            return ["base"]
        if t == "generic_name":
            ident = next((c for c in node.named_children if c.type == "identifier"), None)
            return [self.text(ident)] if ident is not None else None
        if t == "member_access_expression":
            base = self.parts(node.child_by_field_name("expression"))
            name = node.child_by_field_name("name")
            if base is None or name is None:
                return None
            np_ = self.parts(name)
            return [*base, *(np_ or [self.text(name)])]
        if t == "qualified_name":
            base = self.parts(node.child_by_field_name("qualifier"))
            name = node.child_by_field_name("name")
            return [*base, self.text(name)] if base is not None and name is not None else None
        if t == "parenthesized_expression":
            inner = node.named_children
            return self.parts(inner[0]) if inner else None
        return None

    def attributes(self, node: Node) -> list[tuple[str, list[str]]]:
        out: list[tuple[str, list[str]]] = []
        for al in (c for c in node.named_children if c.type == "attribute_list"):
            for attr in (c for c in al.named_children if c.type == "attribute"):
                name = self.text(attr.child_by_field_name("name")).rsplit(".", 1)[-1]
                name = name[: -len("Attribute")] if name.endswith("Attribute") and len(name) > 9 else name
                values: list[str] = []
                arglist = next((c for c in attr.named_children if c.type == "attribute_argument_list"), None)
                for arg in arglist.named_children if arglist is not None else []:
                    for d in arg.named_children:
                        s = self.string_value(d)
                        if s is not None:
                            values.append(s)
                            break
                out.append((name, values))
        return out

    def modifiers(self, node: Node) -> set[str]:
        return {self.text(c) for c in node.named_children if c.type == "modifier"}

    def prepass(self, root: Node) -> None:
        for d in root.named_children:
            if d.type in ("namespace_declaration", "file_scoped_namespace_declaration"):
                name = d.child_by_field_name("name")
                if name is not None:
                    self.namespace_root = self.text(name).split(".")[0]
                break

    def visit(self, node: Node) -> None:
        t = node.type
        if t == "using_directive":
            self.using(node)
        elif t in _CS_TYPES:
            self.type_decl(node)
        elif t == "invocation_expression":
            self.invocation(node)
        elif t == "object_creation_expression":
            p = self.parts(node.child_by_field_name("type"))
            if p:
                self.add_call(p, node)
            self.visit_children(node)
        elif t in ("local_declaration_statement",):
            self.local_decl(node)
        else:
            self.visit_children(node)

    def using(self, node: Node) -> None:
        named = [c for c in node.named_children if c.type in ("identifier", "qualified_name", "generic_name")]
        if not named:
            return
        alias: str | None = None
        has_eq = any(self.text(c) == "=" for c in node.children if not c.is_named)
        if has_eq and len(named) >= 2:
            alias = self.text(named[0])
        target = named[-1]
        module = self.text(target)
        segs = module.split(".")
        resolved_dir: str | None = None
        if self.index is not None:
            for start in (0, 1):
                if len(segs) - start >= 1:
                    resolved_dir = self.index.dir_with_suffix("/".join(segs[start:]))
                    if resolved_dir is not None:
                        break
        internal = resolved_dir is not None or (
            self.namespace_root is not None and segs[0] == self.namespace_root
        )
        self.add_import(
            module,
            node,
            alias=alias,
            resolved_dir=resolved_dir,
            external=not internal,
            package=".".join(segs[:2]),
        )
        if alias:
            self.bind(alias, Binding(kind="module", external=None if internal else module))

    def type_decl(self, node: Node) -> None:
        name_n = node.child_by_field_name("name")
        if name_n is None or self.fn_depth:
            self.visit_body(node, None)
            return
        name = self.text(name_n)
        attrs = self.attributes(node)
        attr_names = [a for a, _ in attrs]
        mods = self.modifiers(node)
        bases: list[str] = []
        bl = next((c for c in node.named_children if c.type == "base_list"), None)
        if bl is not None:
            bases = [self.text(c) for c in bl.named_children if c.type not in ("argument_list",)]
        body = node.child_by_field_name("body")
        kind: SymbolKind = "interface" if node.type == "interface_declaration" else "class"
        sym = self.add_symbol(
            name,
            kind,
            node,
            decorators=attr_names,
            bases=bases,
            exported="public" in mods,
            signature=self.signature(node, body),
        )
        prefix: str | None = None
        is_ctrl = "ApiController" in attr_names or (
            name.endswith("Controller")
            and any(b.split("<")[0] in ("Controller", "ControllerBase") for b in bases)
        )
        if is_ctrl:
            controller = name[: -len("Controller")] if name.endswith("Controller") else name
            route = next((v[0] for a, v in attrs if a == "Route" and v), "")
            prefix = route.replace("[controller]", controller)
            self.add_router(name, "aspnet", node, prefix=prefix)
            self.add_app_object("aspnet")
        self.containers.append(sym.qualname)
        self.scope.append(sym.qualname)
        try:
            for member in body.named_children if body is not None else []:
                if member.type in ("method_declaration", "constructor_declaration"):
                    self.method(member, sym, prefix)
                elif member.type in _CS_TYPES:
                    self.type_decl(member)
                else:
                    self.visit(member)
        finally:
            self.containers.pop()
            self.scope.pop()

    def method(self, member: Node, cls: SymbolDef, prefix: str | None) -> None:
        name_n = member.child_by_field_name("name")
        name = self.text(name_n) if name_n is not None else cls.name
        attrs = self.attributes(member)
        mods = self.modifiers(member)
        body = member.child_by_field_name("body")
        sym = self.add_symbol(
            name,
            "method",
            member,
            parent=cls.qualname,
            decorators=[a for a, _ in attrs],
            exported="public" in mods,
            is_async="async" in mods,
            signature=self.signature(member, body),
        )
        if prefix is not None:
            method_route = next((v[0] for a, v in attrs if a == "Route" and v), None)
            for a, v in attrs:
                verb = _ASPNET_VERBS.get(a)
                if verb is None:
                    continue
                template = v[0] if v else (method_route or "")
                template = template.replace("[action]", name)
                full = (
                    "/" + template.lstrip("~/")
                    if template.startswith(("/", "~/"))
                    else _join_path(prefix, template)
                )
                self.add_route(
                    verb,
                    template or "/",
                    member,
                    "aspnet",
                    router=cls.name,
                    handler=sym.qualname,
                    full_path=full,
                )
        self.visit_body(body, sym.qualname)

    def invocation(self, node: Node) -> None:
        fn = node.child_by_field_name("function")
        p = self.parts(fn)
        arglist = node.child_by_field_name("arguments")
        args = [
            next(iter(a.named_children), a)
            for a in (arglist.named_children if arglist is not None else [])
            if a.type == "argument"
        ]
        if p:
            self.add_call(p, node)
            if len(p) >= 2 and p[-1] in _ASPNET_MAP and args:
                path = self.string_value(args[0])
                if path is not None:
                    h = args[-1] if len(args) >= 2 else None
                    hp = self.parts(h) if h is not None else None
                    self.add_route(
                        _ASPNET_MAP[p[-1]],
                        path,
                        node,
                        "aspnet",
                        router=".".join(p[:-1]),
                        handler_ref=hp,
                    )
                    self.add_app_object("aspnet")
        self.visit_children(node)

    def local_decl(self, node: Node) -> None:
        for d in self.descendants(node, limit=200):
            if d.type == "variable_declarator":
                name = d.child_by_field_name("name") or next(
                    (c for c in d.named_children if c.type == "identifier"), None
                )
                inv = next(
                    (c for c in self.descendants(d, limit=50) if c.type == "invocation_expression"), None
                )
                if name is not None and inv is not None:
                    p = self.parts(inv.child_by_field_name("function"))
                    arglist = inv.child_by_field_name("arguments")
                    args = [
                        next(iter(a.named_children), a)
                        for a in (arglist.named_children if arglist is not None else [])
                        if a.type == "argument"
                    ]
                    if p and len(p) >= 2 and p[-1] == "MapGroup" and args:
                        prefix = self.string_value(args[0])
                        if prefix is not None:
                            self.add_router(self.text(name), "aspnet_group", d)
                            self.fa.mounts.append(
                                MountDef(
                                    parent=".".join(p[:-1]),
                                    target=[self.text(name)],
                                    prefix=prefix,
                                    line=self.line(d),
                                )
                            )
                break
        self.visit_children(node)


